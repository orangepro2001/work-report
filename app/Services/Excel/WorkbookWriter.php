<?php

namespace App\Services\Excel;

use App\Models\Issue;
use App\Models\Member;
use App\Models\Project;
use Carbon\CarbonImmutable;
use Illuminate\Support\Collection;
use PhpOffice\PhpSpreadsheet\NamedRange;
use PhpOffice\PhpSpreadsheet\Spreadsheet;
use PhpOffice\PhpSpreadsheet\Style\Alignment;
use PhpOffice\PhpSpreadsheet\Style\Border;
use PhpOffice\PhpSpreadsheet\Style\Fill;
use PhpOffice\PhpSpreadsheet\Worksheet\PageSetup;
use PhpOffice\PhpSpreadsheet\Worksheet\Worksheet;

/**
 * Assembles the three-sheet workbook of docs/source-rev02.xlsx.
 *
 * Layout, colours and formulas come from docs/excel-schema.md; this class owns the
 * assembly order and the defined names, ReportSheetWriter owns sheet 업무일보.
 */
final class WorkbookWriter
{
    public function __construct(private readonly ReportSheetWriter $report) {}

    /**
     * @param  iterable<Issue>  $issues
     * @param  iterable<Member>  $members
     * @param  iterable<Project>  $projects
     */
    public function build(
        CarbonImmutable $reportDate,
        string $department,
        string $authorName,
        iterable $issues,
        iterable $members,
        iterable $projects,
    ): Spreadsheet {
        $book = new Spreadsheet;
        $book->getProperties()
            ->setCreator($authorName)
            ->setCompany($department)
            ->setTitle($this->title($reportDate))
            ->setSubject('업무일보')
            ->setDescription('Generated by work-report');

        $issues = collect($issues);
        $members = collect($members);
        $projects = collect($projects);

        // The report sheet must be the active one — the workbook opens on it.
        $report = $book->getActiveSheet();
        $this->report->write(
            $report,
            $issues,
            $members,
            $projects,
            $reportDate,
            $department,
            $authorName,
        );

        // Sheet order is part of the document: 업무일보 → 담당자 요약 → 목록.
        $this->writeMemberSummary($book->createSheet(), $members, $reportDate);
        $this->writeLists($book->createSheet(), $members, $projects);

        $this->defineNames($book, $members);

        $book->setActiveSheetIndex(0);

        return $book;
    }

    public function title(CarbonImmutable $date): string
    {
        return config('workreport.title_prefix').' / '.$date->format('ymd');
    }

    /* ------------------------------------------------------------------ */
    /* sheet 목록 */
    /* ------------------------------------------------------------------ */

    /**
     * @param  Collection<int,Member>  $members
     * @param  Collection<int,Project>  $projects
     */
    private function writeLists(Worksheet $sheet, $members, $projects): void
    {
        $sheet->setTitle(config('workreport.excel.sheet_lists', '목록'));

        $widths = ['A' => 2.0, 'B' => 12.0, 'C' => 9.0, 'D' => 3.0, 'E' => 12.0,
            'F' => 3.0, 'G' => 12.0, 'H' => 3.0, 'I' => 14.0, 'J' => 2.0];
        foreach ($widths as $col => $w) {
            $sheet->getColumnDimension($col)->setWidth($w);
        }
        $sheet->getRowDimension(1)->setRowHeight(8.1);
        $sheet->getRowDimension(2)->setRowHeight(33.95);
        $sheet->getRowDimension(3)->setRowHeight(21.95);
        $sheet->getRowDimension(5)->setRowHeight(24.0);

        $sheet->mergeCells('B2:J2');
        $sheet->setCellValue('B2', '목록 / 설정');
        $sheet->getStyle('B2')->applyFromArray([
            'font' => ['name' => '맑은 고딕', 'size' => 20, 'bold' => true, 'color' => ['rgb' => ReportSheetWriter::NAVY]],
            'alignment' => ['horizontal' => Alignment::HORIZONTAL_LEFT, 'vertical' => Alignment::VERTICAL_CENTER],
        ]);
        $sheet->setCellValue('B3', '여기서 고치면 업무일보 드롭다운에 바로 반영됩니다 · 위에서부터 빈칸 없이 입력');
        $sheet->getStyle('B3')->getFont()->setName('맑은 고딕')->getColor()->setRGB(ReportSheetWriter::FAINT);

        $headers = ['B' => '구분', 'C' => '키 약어', 'E' => '상태', 'G' => '우선순위', 'I' => '담당자'];
        foreach ($headers as $col => $text) {
            $sheet->setCellValue("{$col}5", $text);
            $sheet->getStyle("{$col}5")->applyFromArray([
                'font' => ['name' => '맑은 고딕', 'size' => 10, 'bold' => true, 'color' => ['rgb' => 'FFFFFF']],
                'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => ReportSheetWriter::BLUE]],
                'alignment' => ['horizontal' => Alignment::HORIZONTAL_CENTER, 'vertical' => Alignment::VERTICAL_CENTER],
            ]);
        }

        $row = 6;
        foreach (config('workreport.summary_buckets') as $bucket) {
            $sheet->setCellValue("B{$row}", $bucket['label']);
            $sheet->setCellValue("C{$row}", $bucket['abbr']);
            $row++;
        }

        $row = 6;
        foreach (config('workreport.statuses') as $status) {
            $sheet->setCellValue("E{$row}", $status['label']);
            $row++;
        }

        $row = 6;
        foreach (config('workreport.priorities') as $priority) {
            $sheet->setCellValue("G{$row}", $priority['label']);
            $row++;
        }

        // Row 6..20 is the fixed slot range the defined names OFFSET over.
        $row = 6;
        foreach ($members as $member) {
            if ($row > 20) {
                break;
            }
            $sheet->setCellValue("I{$row}", $member->name);
            $row++;
        }

        $sheet->setShowGridlines(false);
    }

    /* ------------------------------------------------------------------ */
    /* sheet 담당자 요약 */
    /* ------------------------------------------------------------------ */

    /**
     * @param  Collection<int,Member>  $members
     */
    private function writeMemberSummary(Worksheet $sheet, $members, CarbonImmutable $reportDate): void
    {
        $sheet->setTitle(config('workreport.excel.sheet_members', '담당자 요약'));

        $widths = ['A' => 2.0, 'B' => 14.0, 'C' => 8.0, 'D' => 8.0, 'E' => 9.0,
            'F' => 8.0, 'G' => 8.0, 'H' => 8.0, 'I' => 11.0, 'J' => 16.0,
            'K' => 16.0, 'L' => 2.0];
        foreach ($widths as $col => $w) {
            $sheet->getColumnDimension($col)->setWidth($w);
        }
        $sheet->getRowDimension(1)->setRowHeight(8.1);
        $sheet->getRowDimension(2)->setRowHeight(33.95);
        $sheet->getRowDimension(3)->setRowHeight(21.95);
        for ($r = 5; $r <= 16; $r++) {
            $sheet->getRowDimension($r)->setRowHeight(21.95);
        }
        $sheet->getRowDimension(19)->setRowHeight(21.95);
        $sheet->getRowDimension(20)->setRowHeight(24.0);
        for ($r = 21; $r <= 30; $r++) {
            $sheet->getRowDimension($r)->setRowHeight(21.95);
        }

        $sheet->mergeCells('B2:L2');
        $sheet->setCellValue('B2', '="담당자별 업무 요약 / "&TEXT(업무일보!$D$3,"YYMMDD")');
        $sheet->getStyle('B2')->applyFromArray([
            'font' => ['name' => '맑은 고딕', 'size' => 20, 'bold' => true, 'color' => ['rgb' => ReportSheetWriter::NAVY]],
            'alignment' => ['horizontal' => Alignment::HORIZONTAL_LEFT, 'vertical' => Alignment::VERTICAL_CENTER],
            'borders' => ['bottom' => ['borderStyle' => Border::BORDER_MEDIUM, 'color' => ['rgb' => ReportSheetWriter::NAVY]]],
        ]);

        $sheet->setCellValue('B3', '업무일보 시트에서 자동 집계 · 공동 담당');
        $sheet->getStyle('B3')->getFont()->setName('맑은 고딕')->getColor()->setRGB(ReportSheetWriter::FAINT);

        $sheet->setCellValue('B5', '■ 담당자별 현황');
        $sheet->getStyle('B5')->applyFromArray([
            'font' => ['name' => '맑은 고딕', 'size' => 12, 'bold' => true, 'color' => ['rgb' => ReportSheetWriter::NAVY]],
        ]);

        $headers = [
            'B' => '담당자', 'C' => '전체', 'D' => '예정', 'E' => '진행 중', 'F' => '완료',
            'G' => '보류', 'H' => '지연', 'I' => 'High 미완료', 'J' => '평균 진행률', 'K' => '완료율',
        ];
        foreach ($headers as $col => $text) {
            $sheet->setCellValue("{$col}6", $text);
            $sheet->getStyle("{$col}6")->applyFromArray([
                'font' => ['name' => '맑은 고딕', 'size' => 10, 'bold' => true, 'color' => ['rgb' => 'FFFFFF']],
                'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => ReportSheetWriter::NAVY]],
                'alignment' => ['horizontal' => Alignment::HORIZONTAL_CENTER, 'vertical' => Alignment::VERTICAL_CENTER, 'wrapText' => true],
                'borders' => [
                    'left' => ['borderStyle' => Border::BORDER_THIN, 'color' => ['rgb' => 'FFFFFF']],
                    'right' => ['borderStyle' => Border::BORDER_THIN, 'color' => ['rgb' => 'FFFFFF']],
                ],
            ]);
        }

        // Rows 7-16: at most ten members, the workbook's own limit.
        $i = 0;
        foreach ($members as $member) {
            if ($i >= 10) {
                break;
            }
            $r = 7 + $i;
            $n = $i + 1;
            $sheet->setCellValue("B{$r}", "=IF(INDEX(담당자목록전체,{$n})=\"\",\"\",INDEX(담당자목록전체,{$n}))");

            $criteria = "\"*\"&\$B{$r}&\"*\",업무일보!\$E\$16:\$E\$76,\"<>\"";
            $sheet->setCellValue("C{$r}", "=IF(\$B{$r}=\"\",\"\",COUNTIFS(업무일보!\$F\$16:\$F\$76,{$criteria}))");
            foreach (['D' => '예정', 'E' => '진행 중', 'F' => '완료', 'G' => '보류'] as $col => $status) {
                $sheet->setCellValue(
                    "{$col}{$r}",
                    "=IF(\$B{$r}=\"\",\"\",COUNTIFS(업무일보!\$F\$16:\$F\$76,{$criteria},업무일보!\$I\$16:\$I\$76,\"{$status}\"))"
                );
            }
            $sheet->setCellValue(
                "H{$r}",
                "=IF(\$B{$r}=\"\",\"\",COUNTIFS(업무일보!\$F\$16:\$F\$76,{$criteria},업무일보!\$I\$16:\$I\$76,\"<>완료\",업무일보!\$L\$16:\$L\$76,\"<\"&업무일보!\$D\$3))"
            );
            $sheet->setCellValue(
                "I{$r}",
                "=IF(\$B{$r}=\"\",\"\",COUNTIFS(업무일보!\$F\$16:\$F\$76,{$criteria},업무일보!\$H\$16:\$H\$76,\"High\",업무일보!\$I\$16:\$I\$76,\"<>완료\"))"
            );
            $sheet->setCellValue(
                "J{$r}",
                "=IF(\$B{$r}=\"\",\"\",IFERROR(AVERAGEIFS(업무일보!\$O\$16:\$O\$76,업무일보!\$F\$16:\$F\$76,\"*\"&\$B{$r}&\"*\",업무일보!\$E\$16:\$E\$76,\"<>\"),0))"
            );
            $sheet->setCellValue("K{$r}", "=IF(\$B{$r}=\"\",\"\",IFERROR(F{$r}/C{$r},0))");

            $sheet->getStyle("B{$r}:K{$r}")->applyFromArray([
                'font' => ['name' => '맑은 고딕', 'size' => 10, 'bold' => false],
                'alignment' => ['horizontal' => Alignment::HORIZONTAL_CENTER, 'vertical' => Alignment::VERTICAL_CENTER],
                'borders' => ['bottom' => ['borderStyle' => Border::BORDER_THIN, 'color' => ['rgb' => ReportSheetWriter::HAIR]]],
            ]);
            $sheet->getStyle("J{$r}")->getNumberFormat()->setFormatCode('0"%"');
            $sheet->getStyle("K{$r}")->getNumberFormat()->setFormatCode('0%');
            foreach (['C', 'D', 'E', 'F', 'G', 'H', 'I'] as $col) {
                $sheet->getStyle("{$col}{$r}")->getNumberFormat()->setFormatCode('0;\-0;"-"');
            }
            $i++;
        }

        // Cross-table: 담당자 × 구분.
        $sheet->setCellValue('B19', '■ 담당자 × 구분 (진행 중 / 전체)');
        $sheet->getStyle('B19')->applyFromArray([
            'font' => ['name' => '맑은 고딕', 'size' => 12, 'bold' => true, 'color' => ['rgb' => ReportSheetWriter::NAVY]],
        ]);

        $sheet->setCellValue('B20', '담당자');
        $sheet->getStyle('B20')->applyFromArray([
            'font' => ['name' => '맑은 고딕', 'size' => 10, 'bold' => true, 'color' => ['rgb' => 'FFFFFF']],
            'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => ReportSheetWriter::NAVY]],
            'alignment' => ['horizontal' => Alignment::HORIZONTAL_CENTER, 'vertical' => Alignment::VERTICAL_CENTER],
        ]);

        $buckets = config('workreport.summary_buckets');
        $anchors = ['C', 'E', 'G', 'I'];
        foreach ($anchors as $idx => $col) {
            if (! isset($buckets[$idx])) {
                continue;
            }
            $next = chr(ord($col) + 1);
            $sheet->mergeCells("{$col}20:{$next}20");
            $sheet->setCellValue("{$col}20", '=INDEX(구분목록전체,'.($idx + 1).')&""');
            $sheet->getStyle("{$col}20:{$next}20")->applyFromArray([
                'font' => ['name' => '맑은 고딕', 'size' => 10, 'bold' => true, 'color' => ['rgb' => 'FFFFFF']],
                'fill' => ['fillType' => Fill::FILL_SOLID, 'startColor' => ['rgb' => ReportSheetWriter::NAVY]],
                'alignment' => ['horizontal' => Alignment::HORIZONTAL_CENTER, 'vertical' => Alignment::VERTICAL_CENTER],
            ]);
        }

        for ($i = 0; $i < 10; $i++) {
            $r = 21 + $i;
            $src = 7 + $i;
            $sheet->setCellValue("B{$r}", "=B{$src}");
            $sheet->getStyle("B{$r}")->getFont()->setBold(true);

            foreach ($anchors as $idx => $col) {
                if (! isset($buckets[$idx])) {
                    continue;
                }
                $next = chr(ord($col) + 1);
                $sheet->mergeCells("{$col}{$r}:{$next}{$r}");
                $sheet->setCellValue(
                    "{$col}{$r}",
                    "=IF(OR(\$B{$r}=\"\",\${$col}\$20=\"\"),\"\",IF(COUNTIFS(업무일보!\$F\$16:\$F\$76,\"*\"&\$B{$r}&\"*\",업무일보!\$E\$16:\$E\$76,\"<>\",업무일보!\$D\$16:\$D\$76,\${$col}\$20)=0,\"\","
                    ."COUNTIFS(업무일보!\$F\$16:\$F\$76,\"*\"&\$B{$r}&\"*\",업무일보!\$E\$16:\$E\$76,\"<>\",업무일보!\$D\$16:\$D\$76,\${$col}\$20,업무일보!\$I\$16:\$I\$76,\"진행 중\")"
                    .'&" / "&'
                    ."COUNTIFS(업무일보!\$F\$16:\$F\$76,\"*\"&\$B{$r}&\"*\",업무일보!\$E\$16:\$E\$76,\"<>\",업무일보!\$D\$16:\$D\$76,\${$col}\$20)))"
                );
            }

            $sheet->getStyle("B{$r}:J{$r}")->applyFromArray([
                'font' => ['name' => '맑은 고딕', 'size' => 10],
                'alignment' => ['horizontal' => Alignment::HORIZONTAL_CENTER, 'vertical' => Alignment::VERTICAL_CENTER],
                'borders' => ['bottom' => ['borderStyle' => Border::BORDER_HAIR, 'color' => ['rgb' => ReportSheetWriter::HAIR]]],
            ]);
        }

        // The reference sheet has no print area; landscape only.
        $sheet->getPageSetup()->setOrientation(PageSetup::ORIENTATION_LANDSCAPE);
        $sheet->getPageSetup()->setFitToHeight(0);
        $sheet->setShowGridlines(false);
    }

    /* ------------------------------------------------------------------ */

    /**
     * Workbook-level names the formulas use. Ranges are deliberately the full
     * fixed slots (rows 6-20) rather than a dynamic OFFSET: PhpSpreadsheet writes
     * static definitions and Excel resolves them identically for COUNTIFS/VLOOKUP.
     *
     * @param  Collection<int,Member>  $members
     */
    private function defineNames(Spreadsheet $book, $members): void
    {
        $lists = config('workreport.excel.sheet_lists', '목록');

        $book->addNamedRange(new NamedRange('구분목록', $book->getSheetByName($lists), "\${$lists}!\$B\$6:\$B\$20"));
        $book->addNamedRange(new NamedRange('구분목록전체', $book->getSheetByName($lists), $lists.'!$B$6:$B$20'));
        $book->addNamedRange(new NamedRange('구분표', $book->getSheetByName($lists), $lists.'!$B$6:$C$20'));
        $book->addNamedRange(new NamedRange('담당자목록', $book->getSheetByName($lists), $lists.'!$I$6:$I$20'));
        $book->addNamedRange(new NamedRange('담당자목록전체', $book->getSheetByName($lists), $lists.'!$I$6:$I$20'));
        $book->addNamedRange(new NamedRange('상태목록', $book->getSheetByName($lists), $lists.'!$E$6:$E$20'));
        $book->addNamedRange(new NamedRange('우선순위목록', $book->getSheetByName($lists), $lists.'!$G$6:$G$20'));
    }
}
